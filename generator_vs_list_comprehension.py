"""
리스트 컴프리헨션은 리스트 전체를 메모리에 한 번에 생성([ ])하여 즉시 사용하고, 
제너레이터 표현식은 '()'를 사용하여 필요할 때마다 값을 하나씩 생성(Lazy Evaluation)합니다. 

결과적으로 
리스트 컴프리헨션은 대량 데이터 처리에 메모리 낭비가 심한 반면, 
제너레이터는 메모리 효율이 매우 높습니다. 

주요 차이점 요약
    구문 및 반환값:
    리스트 컴프리헨션: [x for x in range(10)] → list 객체 반환
    제너레이터 표현식: (x for x in range(10)) → generator 객체 반환

메모리 사용량:
    리스트: 모든 요소를 메모리에 적재 (대규모 데이터 시 메모리 부족 위험)
    제너레이터: 현재 계산 중인 하나의 요소만 메모리에 유지 (효율적)

평가 방식 (Evaluation):
    리스트: 즉시 실행 (Eager Evaluation)
    제너레이터: 호출될 때만 실행 (Lazy Evaluation)

재사용성:
    리스트: 여러 번 반복 가능
    제너레이터: 한 번만 소비됨 

언제 무엇을 사용할까?
    
    리스트 컴프리헨션: 
        결과 리스트를 여러 번 반복해서 사용해야 하거나, 데이터 양이 적을 때.
    
    제너레이터 표현식: 
        대용량 데이터를 처리하거나, 단 한 번만 순회하면 될 때.
        즉시 전체 리스트가 필요하지 않을 때. 
"""

# 리스트 컴프리헨션
squares_list = [x**2 for x in range(10)] 
print(squares_list) #[0, 1, 4, 9, 16, 25, 36, 49, 64, 81]

# 제너레이터 표현식
squares_gen = (x**2 for x in range(10))
print(squares_gen) #제네레이터 객체, <generator object <genexpr> at 0x000002105F888E10>
for i in squares_gen: 
    print(i, end='/') #0/1/4/9/16/25/36/49/64/81/