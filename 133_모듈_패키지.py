"""
패키지

my_package/          # 패키지 디렉터리
    ├── __init__.py  # 패키지 초기화 파일
    ├── module1.py   # 모듈 파일
    └── sub_package/ # 하위 패키지
        ├── __init__.py
        └── module2.py


디렉터리 이름: 패키지의 이름이 됩니다.
    __init__.py 파일: 해당 디렉터리를 파이썬 패키지로 인식하게 만드는 필수 파일입니다 
        (파이썬 3.3 이후부터는 없어도 동작하는 네임스페이스 패키지가 지원되나, 
        하위 호환성과 명시적 선언을 위해 보통 포함합니다).
    
    모듈(.py): 함수, 클래스, 변수 등이 담긴 개별 파이썬 파일입니다.
    
    하위 패키지: 디렉터리 안에 다시 디렉터리를 만들어 계층적으로 관리할 수 있습니다.    

배포 및 유통 형식 (Distribution Formats)

소스 배포판 (Sdist, Source Distribution):
    확장자: .tar.gz
    소스 코드 원본 형태입니다. 설치 시 사용자의 환경에서 빌드가 진행됩니다.

바이너리 배포판 (Wheel, 휠):
    확장자: .whl미리 빌드된 표준 배포 형식입니다. 
    설치 속도가 빠르고 컴파일 과정이 필요 없어 현대 파이썬 배포의 표준으로 쓰입니다.


__init__.py
    __init__.py 파일은 파이썬 패키지를 초기화하고 관리하는 핵심 파일입니다. 
    주요 역할은 크게 3가지로 나뉩니다.

    1. 디렉터리를 '패키지'로 인식하게 함파이썬은 어떤 디렉터리 안에 __init__.py 파일이 있으면, 
        그 디렉터리를 일반 폴더가 아닌 파이썬 패키지로 취급합니다.

        💡 참고: 
        파이썬 3.3 버전부터는 이 파일이 없어도 패키지로 인식하는 
        '네임스페이스 패키지' 기능이 도입되었습니다. 
        하지만 하위 버전 호환성과 명시적인 패키지 선언, 
        그리고 초기화 기능들을 활용하기 위해 여전히 생성이 권장됩니다. 
        내용이 필요 없다면 비어 있는 파일로 두어도 괜찮습니다.

    2. 패키지 수입(import) 시 초기화 코드 실행사용자가 import my_package와 같이 패키지를 불러올 때, 
    __init__.py 안에 적어둔 코드가 가장 먼저 최초 1회 자동 실행됩니다.
    이를 통해 패키지가 구동되기 전 필요한 설정이나 로깅, 환경 변수 로드 등의 작업을 수행할 수 있습니다.

    3. 패키지 내보내기(Export) 제어 및 편의성 제공외부에서 패키지 내부 모듈을 더 쉽게 가져다 쓸 수 있도록 
    경로를 단축(Exposing)해 주거나, 가져갈 수 있는 기능을 제한할 수 있습니다.

        - import 경로 단축:깊은 구조에 있는 모듈을 쉽게 가져오게 만들 수 있습니다.
            # __init__.py 내부
            from .sub_folder.module1 import my_function

            # 사용
            from my_package import my_function

        __all__ 변수를 통한 접근 제어:__init__.py 파일 안에 __all__이라는 리스트 변수를 정의하면, 
        외부에서 와일드카드(from my_package import *)로 불러올 때 허용할 모듈이나 함수만 지정할 수 있습니다.

            # __init__.py 내부
            __all__ = ['module1', 'module2']  # module3은 외부 import * 에서 제외됨


.sub_folder.module1 의 앞의 '.'은 무슨 의미?

  앞에 붙은 .은 현재 디렉터리(폴더)를 뜻하는 상대 경로(Relative Path) 표시입니다.
  파이썬 패키지 내부에서 다른 모듈이나 하위 패키지를 참조할 때, 자기 자신의 위치를 기준으로 경로를 찾기 위해 사용합니다. 
  (Unix/Linux 터미널 명령어나 웹 경로에서 현재 폴더를 .으로 표시하는 것과 같은 개념입니다.)

  📌 점(.) 개수에 따른 의미점의 개수에 따라 탐색하는 디렉터리의 위치가 위로 올라갑니다.
  . (점 1개): 현재 파일이 위치한 디렉터리 (Current Directory)
  .. (점 2개): 현재 디렉터리의 상위(부모) 디렉터리 (Parent Directory)
  ... (점 3개): 상위 디렉터리의 상위(조부모) 디렉터리


  .(공백) 여부(같은 의미)
    # 공백 없음 (가능)
    from .import module2

    # 공백 있음 (PEP 8 권장 표준)
    from . import module2

"""
